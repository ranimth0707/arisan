// Generates api/_program.js from the IDL that ships with the app.
//
// Kept inside app/ on purpose so this folder builds standalone, which is how
// Vercel deploys it. Reading src/lib/idl.json rather than the Anchor target/
// directory matters twice over: target/ is gitignored so it does not exist on a
// build server, and the relayer must agree with the exact IDL the frontend was
// compiled against.
//
// Generating a module rather than reading JSON at runtime also avoids relying
// on Vercel's file tracer spotting a dynamic fs read inside a function.

import fs from "node:fs";

const idl = JSON.parse(
  fs.readFileSync(new URL("../src/lib/idl.json", import.meta.url), "utf8"),
);

const entries = idl.instructions
  .map((ix) => `  ${JSON.stringify(ix.name)}: [${ix.discriminator.join(", ")}],`)
  .join("\n");

fs.writeFileSync(
  new URL("../api/_program.js", import.meta.url),
  `// GENERATED by scripts/gen-relayer-constants.mjs. Do not edit by hand.

export const PROGRAM_ADDRESS = ${JSON.stringify(idl.address)};

export const DISCRIMINATORS = {
${entries}
};
`,
);

console.log(`wrote ${idl.instructions.length} discriminators for ${idl.address}`);
