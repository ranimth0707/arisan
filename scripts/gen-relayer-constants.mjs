// Generates app/api/_program.js from the IDL that ships with the app.
//
// Two reasons this reads app/src/lib/idl.json rather than target/idl:
// target/ is gitignored, so it does not exist on a build server, and the
// relayer must agree with the exact IDL the frontend was built against.
//
// The relayer functions need only the program id and the instruction
// discriminators. Generating a plain module rather than reading JSON at runtime
// also avoids relying on Vercel's file tracer noticing a dynamic fs read.

import fs from "node:fs";

const source = new URL("../app/src/lib/idl.json", import.meta.url);
const idl = JSON.parse(fs.readFileSync(source, "utf8"));

const entries = idl.instructions
  .map((ix) => `  ${JSON.stringify(ix.name)}: [${ix.discriminator.join(", ")}],`)
  .join("\n");

fs.writeFileSync(
  new URL("../app/api/_program.js", import.meta.url),
  `// GENERATED by scripts/gen-relayer-constants.mjs. Do not edit by hand.

export const PROGRAM_ADDRESS = ${JSON.stringify(idl.address)};

export const DISCRIMINATORS = {
${entries}
};
`,
);

console.log(`wrote ${idl.instructions.length} discriminators for ${idl.address}`);
